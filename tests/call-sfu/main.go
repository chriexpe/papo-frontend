var listen = flag.String("listen", "127.0.0.1:18765", "HTTP/WebSocket listener")
var advertise = flag.String("advertise", "", "optional host ICE address override")
var mediaDir = flag.String("media", "", "fixture media generated by run.sh")

const channelID = "00000000-0000-4000-8000-000000000010"
const ownID = "00000000-0000-4000-8000-000000000001"

var packetsAudio atomic.Uint64
var packetsVideo atomic.Uint64
var joined atomic.Uint64
var left atomic.Uint64
var iceDelay atomic.Int64
var peers sync.Map
var upgrader = websocket.Upgrader{CheckOrigin: func(*http.Request) bool { return true }}

type peer struct {
	socket *websocket.Conn
	mu     sync.Mutex
	pc     *webrtc.PeerConnection
	media  *roomMedia
	id     string
	stop   chan struct{}
	once   sync.Once
}

func (p *peer) send(value any) { p.mu.Lock(); defer p.mu.Unlock(); _ = p.socket.WriteJSON(value) }
func (p *peer) closeMedia() {
	if p.pc != nil {
		_ = p.pc.Close()
		p.pc = nil
	}
	if p.stop != nil {
		p.once.Do(func() { close(p.stop) })
	}
}
func (p *peer) join(channel string) error {
	p.closeMedia()
	p.once = sync.Once{}
	p.stop = make(chan struct{})
	p.media = &roomMedia{}
	p.id = fmt.Sprintf("fixture-peer-%d", joined.Add(1))
	id := p.id
	emit := p.owner(channel, id)

	settings := webrtc.SettingEngine{}
	settings.SetNetworkTypes([]webrtc.NetworkType{webrtc.NetworkTypeUDP4})
	settings.SetIncludeLoopbackCandidate(true)
	if *advertise != "" {
		settings.SetNAT1To1IPs([]string{*advertise}, webrtc.ICECandidateTypeHost)
	}
	engine := &webrtc.MediaEngine{}
	for _, codec := range []struct {
		kind       webrtc.RTPCodecType
		parameters webrtc.RTPCodecParameters
	}{
		{webrtc.RTPCodecTypeAudio, webrtc.RTPCodecParameters{
			RTPCodecCapability: webrtc.RTPCodecCapability{MimeType: webrtc.MimeTypeOpus, ClockRate: 48000, Channels: 2},
			PayloadType:        111,
		}},
		{webrtc.RTPCodecTypeVideo, webrtc.RTPCodecParameters{
			RTPCodecCapability: webrtc.RTPCodecCapability{MimeType: webrtc.MimeTypeVP8, ClockRate: 90000},
			PayloadType:        96,
		}},
	} {
		if err := engine.RegisterCodec(codec.parameters, codec.kind); err != nil {
			return err
		}
	}
	if err := engine.RegisterHeaderExtension(webrtc.RTPHeaderExtensionCapability{URI: videoRouteURI}, webrtc.RTPCodecTypeVideo); err != nil {
		return err
	}
	api := webrtc.NewAPI(webrtc.WithMediaEngine(engine), webrtc.WithSettingEngine(settings),
		webrtc.WithInterceptorRegistry(&interceptor.Registry{}))
	pc, err := api.NewPeerConnection(webrtc.Configuration{})
	if err != nil {
		return err
	}
	p.pc = pc
	// Same m-line order as the production SFU: upstream mic, six video and eight audio slots.
	_, err = pc.AddTransceiverFromKind(webrtc.RTPCodecTypeAudio, webrtc.RTPTransceiverInit{Direction: webrtc.RTPTransceiverDirectionRecvonly})
	if err != nil {
		return err
	}
	for i := 0; i < 6; i++ {
		track, err := webrtc.NewTrackLocalStaticRTP(webrtc.RTPCodecCapability{MimeType: webrtc.MimeTypeVP8, ClockRate: 90000}, fmt.Sprintf("papo-video-%d", i), "papo-video")
		if err != nil {
			return err
		}
		tr, err := pc.AddTransceiverFromTrack(track, webrtc.RTPTransceiverInit{Direction: webrtc.RTPTransceiverDirectionSendonly})
		if err != nil {
			return err
		}
		p.media.video[i] = videoSlot{track: track, next: 65531, payloader: codecs.VP8Payloader{EnablePictureID: true}}
		go func() {
			buf := make([]byte, 1500)
			for {
				if _, _, err := tr.Sender().Read(buf); err != nil {
					return
				}
			}
		}()
	}
	for i := 0; i < 8; i++ {
		track, err := webrtc.NewTrackLocalStaticSample(webrtc.RTPCodecCapability{MimeType: webrtc.MimeTypeOpus, ClockRate: 48000, Channels: 2}, fmt.Sprintf("papo-audio-%d", i), "papo-audio")
		if err != nil {
			return err
		}
		tr, err := pc.AddTransceiverFromTrack(track, webrtc.RTPTransceiverInit{Direction: webrtc.RTPTransceiverDirectionSendonly})
		if err != nil {
			return err
		}
		p.media.audio[i] = track
		go func() {
			buf := make([]byte, 1500)
			for {
				if _, _, err := tr.Sender().Read(buf); err != nil {
					return
				}
			}
		}()
	}
	pc.OnICECandidate(func(c *webrtc.ICECandidate) {
		if c != nil {
			v := c.ToJSON()
			emit(map[string]any{"type": "voice_ice_candidate", "candidate": v.Candidate, "sdp_mline_index": v.SDPMLineIndex})
		}
	})
	pc.OnTrack(func(track *webrtc.TrackRemote, _ *webrtc.RTPReceiver) {
		for {
			_, _, err := track.ReadRTP()
			if err != nil {
				return
			}
			if track.Kind() == webrtc.RTPCodecTypeAudio {
				packetsAudio.Add(1)
			} else {
				packetsVideo.Add(1)
			}
		}
	})
	stop, media := p.stop, p.media
	pc.OnConnectionStateChange(func(state webrtc.PeerConnectionState) {
		log.Printf("fixture PeerConnection %s", state)
		if state == webrtc.PeerConnectionStateConnected {
			go media.sendSamples(stop, emit)
		}
	})
	emit(map[string]any{"type": "voice_joined", "video_codec": "vp8", "members": []any{
		member(ownID, true, false, false), member(red, false, true, false),
		member(green, false, true, false), member(blue, false, true, true),
	}, "active_speakers": []string{red}})
	return nil
}

func (p *peer) owner(channel, id string) func(map[string]any) {
	return func(event map[string]any) {
		event["channel_id"] = channel
		event["peer_id"] = id
		p.send(event)
	}
}

func trackTarget(user, kind string) publisher { return publisher{user: user, kind: kind} }

func member(id string, muted, camera, screen bool) map[string]any {
	return map[string]any{"user_id": id, "muted": muted, "camera_on": camera, "screen_sharing": screen}
}

func socket(w http.ResponseWriter, r *http.Request) {
	ownMuted, ownCamera := true, false
	var pendingICE []webrtc.ICECandidateInit
	ws, err := upgrader.Upgrade(w, r, nil)
	if err != nil {
		return
	}
	p := &peer{socket: ws}
	peers.Store(p, true)
	defer func() { p.closeMedia(); peers.Delete(p); ws.Close() }()
	p.send(map[string]any{"type": "presence_sync", "members": []any{map[string]any{"user_id": red, "status": "online", "user_voice": []string{channelID}}}})
	p.send(map[string]any{"type": "voice_state_update", "channel_id": channelID, "user_id": red, "muted": false, "camera_on": true, "screen_sharing": false})
	for {
		var m map[string]json.RawMessage
		if err := ws.ReadJSON(&m); err != nil {
			return
		}
		var kind, channel, sdp string
		_ = json.Unmarshal(m["type"], &kind)
		_ = json.Unmarshal(m["channel_id"], &channel)
		_ = json.Unmarshal(m["sdp"], &sdp)
		switch kind {
		case "heartbeat":
			p.send(map[string]any{"type": "heartbeat_ack"})
		case "voice_join":
			if err := p.join(channel); err != nil {
				log.Print(err)
			}
		case "voice_leave":
			p.closeMedia()
			left.Add(1)
			time.Sleep(250 * time.Millisecond) // Delayed acknowledgement exposes rapid-rejoin races.
			p.send(map[string]any{"type": "voice_leave", "channel_id": channel, "user_id": ownID, "peer_id": p.id})
		case "voice_offer":
			if p.pc == nil {
				continue
			}
			if err := p.pc.SetRemoteDescription(webrtc.SessionDescription{Type: webrtc.SDPTypeOffer, SDP: sdp}); err != nil {
				log.Print(err)
				continue
			}
			for _, c := range pendingICE {
				_ = p.pc.AddICECandidate(c)
			}
			pendingICE = nil
			answer, err := p.pc.CreateAnswer(nil)
			if err != nil {
				log.Print(err)
				continue
			}
			if err = p.pc.SetLocalDescription(answer); err != nil {
				log.Print(err)
				continue
			}
			p.owner(channel, p.id)(map[string]any{"type": "voice_answer", "sdp": answer.SDP})
		case "voice_ice_candidate":
			if p.pc != nil {
				var c webrtc.ICECandidateInit
				encoded, _ := json.Marshal(m)
				_ = json.Unmarshal(encoded, &c)
				if p.pc.RemoteDescription() == nil {
					pendingICE = append(pendingICE, c)
					continue
				}
				if err := p.pc.AddICECandidate(c); err != nil {
					log.Print(err)
				}
			}
		case "track_subscribe", "track_unsubscribe":
			var publisher, mediaKind string
			_ = json.Unmarshal(m["publisher_id"], &publisher)
			_ = json.Unmarshal(m["kind"], &mediaKind)
			if p.media != nil {
				p.media.subscribe(p.owner(channel, p.id), trackTarget(publisher, mediaKind), kind == "track_subscribe")
			}
		case "voice_mute":
			var muted bool
			_ = json.Unmarshal(m["muted"], &muted)
			ownMuted = muted
			p.send(map[string]any{"type": "voice_state_update", "channel_id": channel, "user_id": ownID, "muted": muted, "camera_on": ownCamera, "screen_sharing": false})
		case "voice_camera":
			var on bool
			_ = json.Unmarshal(m["on"], &on)
			ownCamera = on
			p.send(map[string]any{"type": "voice_state_update", "channel_id": channel, "user_id": ownID, "muted": ownMuted, "camera_on": on, "screen_sharing": false})
		}
	}
}
func httpAPI(w http.ResponseWriter, r *http.Request) {
	log.Printf("%s %s", r.Method, r.URL.Path)
	w.Header().Set("Content-Type", "application/json")
	var value any = map[string]any{}
	switch r.URL.Path {
	case "/auth/login":
		http.SetCookie(w, &http.Cookie{Name: "Auth", Value: "local-call-fixture", Path: "/", HttpOnly: true})
		value = map[string]any{"user": map[string]any{"id": ownID, "username": "tester"}}
	case "/auth/whoami":
		value = map[string]any{"id": ownID, "username": "tester", "nickname": "Call tester", "settings": map[string]any{"version": 1, "config": map[string]any{}}}
	case "/server":
		value = map[string]any{"id": "call-fixture", "name": "Local call test", "public": true, "owner_id": ownID}
	case "/channels":
		value = map[string]any{"channels": []any{map[string]any{"id": channelID, "name": "Fixture voice", "type": "voice"}, map[string]any{"id": "chat", "name": "Fixture chat", "type": "text"}}}
	case "/users":
		value = map[string]any{"users": []any{map[string]any{"id": ownID, "username": "tester", "nickname": "Call tester"}, map[string]any{"id": red, "username": "ana", "nickname": "Ana"}}}
	case "/users/profile_batch":
		value = map[string]any{"profiles": []any{}}
	case "/users/blocks":
		value = map[string]any{"users": []any{}}
	case "/roles":
		value = map[string]any{"roles": []any{}}
	case "/emojis":
		value = map[string]any{"emojis": []any{}, "has_more": false}
	case "/dms":
		value = map[string]any{"dms": []any{}}
	case "/control/ice-delay":
		var ms int64
		_, _ = fmt.Sscan(r.URL.Query().Get("ms"), &ms)
		iceDelay.Store(ms)
	case "/voice/ice-servers":
		time.Sleep(time.Duration(iceDelay.Load()) * time.Millisecond)
		value = map[string]any{"ice_servers": []any{}}
	case "/channels/chat/messages", "/channels/voice/messages":
		value = map[string]any{"messages": []any{}, "has_more": false}
	case "/stats":
		value = map[string]any{"audio": packetsAudio.Load(), "video": packetsVideo.Load(), "joins": joined.Load(), "leaves": left.Load()}
	case "/control/kick":
		peers.Range(func(k, v any) bool {
			p := k.(*peer)
			p.socket.Close()
			return true
		})
	case "/control/disconnect":
		peers.Range(func(k, v any) bool { k.(*peer).socket.Close(); return true })
	default:
		if r.URL.Path == "/ws" {
			socket(w, r)
			return
		}
	}
	_ = json.NewEncoder(w).Encode(value)
}
