var listen = flag.String("listen", "127.0.0.1:18765", "HTTP/WebSocket listener")
var advertise = flag.String("advertise", "10.0.2.2", "host ICE address reachable from the emulator")
var videoFile = flag.String("video", "", "VP8 IVF sample; generated by run.sh")
var packetsAudio atomic.Uint64
var packetsVideo atomic.Uint64
var joined atomic.Uint64
var left atomic.Uint64
var iceDelay atomic.Int64
var peers sync.Map
var upgrader = websocket.Upgrader{CheckOrigin: func(*http.Request) bool { return true }}

type videoSlots struct {
	tracks  [6]*webrtc.TrackLocalStaticSample
	enabled [6]atomic.Bool
	keys    [6]string
	mu      sync.Mutex
}

func (v *videoSlots) subscribe(key string, enabled bool) {
	v.mu.Lock()
	defer v.mu.Unlock()
	for i, value := range v.keys {
		if value == key {
			v.enabled[i].Store(enabled)
			if !enabled {
				v.keys[i] = ""
			}
			return
		}
	}
	if enabled {
		for i, value := range v.keys {
			if value == "" {
				v.keys[i] = key
				v.enabled[i].Store(true)
				return
			}
		}
	}
}

type peer struct {
	socket *websocket.Conn
	mu     sync.Mutex
	pc     *webrtc.PeerConnection
	video  *videoSlots
	audio  *webrtc.TrackLocalStaticSample
	stop   chan struct{}
	once   sync.Once
}

func (p *peer) send(value any) { p.mu.Lock(); defer p.mu.Unlock(); _ = p.socket.WriteJSON(value) }
func (p *peer) closeMedia() {
	if p.pc != nil {
		_ = p.pc.Close()
		p.pc = nil
	}
	if p.stop != nil {
		p.once.Do(func() { close(p.stop) })
	}
}
func (p *peer) join(channel string) error {
	p.closeMedia()
	p.once = sync.Once{}
	p.stop = make(chan struct{})
	p.video = &videoSlots{}

	settings := webrtc.SettingEngine{}
	settings.SetNetworkTypes([]webrtc.NetworkType{webrtc.NetworkTypeUDP4})
	settings.SetIncludeLoopbackCandidate(true)
	if *advertise != "" {
		settings.SetNAT1To1IPs([]string{*advertise}, webrtc.ICECandidateTypeHost)
	}
	engine := &webrtc.MediaEngine{}
	if err := engine.RegisterDefaultCodecs(); err != nil {
		return err
	}
	api := webrtc.NewAPI(webrtc.WithMediaEngine(engine), webrtc.WithSettingEngine(settings))
	pc, err := api.NewPeerConnection(webrtc.Configuration{})
	if err != nil {
		return err
	}
	p.pc = pc
	// Same m-line order as the production SFU: upstream mic, six video and eight audio slots.
	_, err = pc.AddTransceiverFromKind(webrtc.RTPCodecTypeAudio, webrtc.RTPTransceiverInit{Direction: webrtc.RTPTransceiverDirectionRecvonly})
	if err != nil {
		return err
	}
	for i := 0; i < 6; i++ {
		track, err := webrtc.NewTrackLocalStaticSample(webrtc.RTPCodecCapability{MimeType: webrtc.MimeTypeVP8, ClockRate: 90000}, fmt.Sprintf("papo-video-%d", i), "papo-video")
		if err != nil {
			return err
		}
		tr, err := pc.AddTransceiverFromTrack(track, webrtc.RTPTransceiverInit{Direction: webrtc.RTPTransceiverDirectionSendonly})
		if err != nil {
			return err
		}
		p.video.tracks[i] = track
		go func() {
			buf := make([]byte, 1500)
			for {
				if _, _, err := tr.Sender().Read(buf); err != nil {
					return
				}
			}
		}()
	}
	for i := 0; i < 8; i++ {
		track, err := webrtc.NewTrackLocalStaticSample(webrtc.RTPCodecCapability{MimeType: webrtc.MimeTypeOpus, ClockRate: 48000, Channels: 2}, fmt.Sprintf("papo-audio-%d", i), "papo-audio")
		if err != nil {
			return err
		}
		tr, err := pc.AddTransceiverFromTrack(track, webrtc.RTPTransceiverInit{Direction: webrtc.RTPTransceiverDirectionSendonly})
		if err != nil {
			return err
		}
		if i == 0 {
			p.audio = track
		}
		go func() {
			buf := make([]byte, 1500)
			for {
				if _, _, err := tr.Sender().Read(buf); err != nil {
					return
				}
			}
		}()
	}
	pc.OnICECandidate(func(c *webrtc.ICECandidate) {
		if c != nil {
			v := c.ToJSON()
			p.send(map[string]any{"type": "voice_ice_candidate", "channel_id": channel, "candidate": v.Candidate, "sdp_mline_index": v.SDPMLineIndex})
		}
	})
	pc.OnTrack(func(track *webrtc.TrackRemote, _ *webrtc.RTPReceiver) {
		for {
			_, _, err := track.ReadRTP()
			if err != nil {
				return
			}
			if track.Kind() == webrtc.RTPCodecTypeAudio {
				packetsAudio.Add(1)
			} else {
				packetsVideo.Add(1)
			}
		}
	})
	stop, slots, audio := p.stop, p.video, p.audio
	pc.OnConnectionStateChange(func(state webrtc.PeerConnectionState) {
		log.Printf("fixture PeerConnection %s", state)
		if state == webrtc.PeerConnectionStateConnected {
			go p.sendSamples(stop, slots, audio)
			p.send(map[string]any{"type": "voice_audio_routes", "channel_id": channel, "routes": []any{map[string]any{"track_id": "papo-audio-0", "user_id": "ana"}}})
			p.send(map[string]any{"type": "active_speaker_update", "channel_id": channel, "user_ids": []string{"ana"}})
		}
	})
	joined.Add(1)
	p.send(map[string]any{"type": "voice_joined", "channel_id": channel, "members": []any{member("me", true, false), member("ana", false, true)}, "active_speakers": []string{"ana"}})
	return nil
}
func member(id string, muted, camera bool) map[string]any {
	return map[string]any{"user_id": id, "muted": muted, "camera_on": camera, "screen_sharing": id == "ana"}
}
func (p *peer) sendSamples(stop <-chan struct{}, slots *videoSlots, audio *webrtc.TrackLocalStaticSample) {
	// Valid Opus silence, independent of any host microphone or audio device.
	go func() {
		t := time.NewTicker(20 * time.Millisecond)
		defer t.Stop()
		for {
			select {
			case <-stop:
				return
			case <-t.C:
				_ = audio.WriteSample(media.Sample{Data: []byte{0xf8, 0xff, 0xfe}, Duration: 20 * time.Millisecond})
			}
		}
	}()
	for {
		f, err := os.Open(*videoFile)
		if err != nil {
			log.Print(err)
			return
		}
		reader, _, err := ivfreader.NewWith(f)
		if err != nil {
			f.Close()
			return
		}
		for {
			frame, _, err := reader.ParseNextFrame()
			if err != nil {
				break
			}
			select {
			case <-stop:
				f.Close()
				return
			case <-time.After(100 * time.Millisecond):
			}
			for i, track := range slots.tracks {
				if slots.enabled[i].Load() {
					_ = track.WriteSample(media.Sample{Data: frame, Duration: 100 * time.Millisecond})
				}
			}
		}
		f.Close()
	}
}
func socket(w http.ResponseWriter, r *http.Request) {
	ownMuted, ownCamera := true, false
	var pendingICE []webrtc.ICECandidateInit
	ws, err := upgrader.Upgrade(w, r, nil)
	if err != nil {
		return
	}
	p := &peer{socket: ws}
	peers.Store(p, true)
	defer func() { p.closeMedia(); peers.Delete(p); ws.Close() }()
	p.send(map[string]any{"type": "presence_sync", "members": []any{map[string]any{"user_id": "ana", "status": "online", "user_voice": []string{"voice"}}}})
	p.send(map[string]any{"type": "voice_state_update", "channel_id": "voice", "user_id": "ana", "muted": false, "camera_on": true, "screen_sharing": false})
	for {
		var m map[string]json.RawMessage
		if err := ws.ReadJSON(&m); err != nil {
			return
		}
		var kind, channel, sdp string
		_ = json.Unmarshal(m["type"], &kind)
		_ = json.Unmarshal(m["channel_id"], &channel)
		_ = json.Unmarshal(m["sdp"], &sdp)
		switch kind {
		case "heartbeat":
			p.send(map[string]any{"type": "heartbeat_ack"})
		case "voice_join":
			if err := p.join(channel); err != nil {
				log.Print(err)
			}
		case "voice_leave":
			p.closeMedia()
			left.Add(1)
			time.Sleep(250 * time.Millisecond) // Delayed acknowledgement exposes rapid-rejoin races.
			p.send(map[string]any{"type": "voice_leave", "channel_id": channel, "user_id": "me"})
		case "voice_offer":
			if p.pc == nil {
				continue
			}
			if err := p.pc.SetRemoteDescription(webrtc.SessionDescription{Type: webrtc.SDPTypeOffer, SDP: sdp}); err != nil {
				log.Print(err)
				continue
			}
			for _, c := range pendingICE {
				_ = p.pc.AddICECandidate(c)
			}
			pendingICE = nil
			answer, err := p.pc.CreateAnswer(nil)
			if err != nil {
				log.Print(err)
				continue
			}
			if err = p.pc.SetLocalDescription(answer); err != nil {
				log.Print(err)
				continue
			}
			p.send(map[string]any{"type": "voice_answer", "channel_id": channel, "sdp": answer.SDP})
		case "voice_ice_candidate":
			if p.pc != nil {
				var c webrtc.ICECandidateInit
				encoded, _ := json.Marshal(m)
				_ = json.Unmarshal(encoded, &c)
				if p.pc.RemoteDescription() == nil {
					pendingICE = append(pendingICE, c)
					continue
				}
				if err := p.pc.AddICECandidate(c); err != nil {
					log.Print(err)
				}
			}
		case "track_subscribe", "track_unsubscribe":
			var publisher, mediaKind string
			_ = json.Unmarshal(m["publisher_id"], &publisher)
			_ = json.Unmarshal(m["kind"], &mediaKind)
			if p.video != nil {
				p.video.subscribe(publisher+"/"+mediaKind, kind == "track_subscribe")
			}
		case "voice_mute":
			var muted bool
			_ = json.Unmarshal(m["muted"], &muted)
			ownMuted = muted
			p.send(map[string]any{"type": "voice_state_update", "channel_id": channel, "user_id": "me", "muted": muted, "camera_on": ownCamera, "screen_sharing": false})
		case "voice_camera":
			var on bool
			_ = json.Unmarshal(m["on"], &on)
			ownCamera = on
			p.send(map[string]any{"type": "voice_state_update", "channel_id": channel, "user_id": "me", "muted": ownMuted, "camera_on": on, "screen_sharing": false})
		}
	}
}
func httpAPI(w http.ResponseWriter, r *http.Request) {
	log.Printf("%s %s", r.Method, r.URL.Path)
	w.Header().Set("Content-Type", "application/json")
	var value any = map[string]any{}
	switch r.URL.Path {
	case "/auth/login":
		http.SetCookie(w, &http.Cookie{Name: "Auth", Value: "local-call-fixture", Path: "/", HttpOnly: true})
		value = map[string]any{"user": map[string]any{"id": "me", "username": "tester"}}
	case "/auth/whoami":
		value = map[string]any{"id": "me", "username": "tester", "nickname": "Call tester", "settings": map[string]any{"version": 1, "config": map[string]any{}}}
	case "/server":
		value = map[string]any{"id": "call-fixture", "name": "Local call test", "public": true, "owner_id": "me"}
	case "/channels":
		value = map[string]any{"channels": []any{map[string]any{"id": "voice", "name": "Fixture voice", "type": "voice"}, map[string]any{"id": "chat", "name": "Fixture chat", "type": "text"}}}
	case "/users":
		value = map[string]any{"users": []any{map[string]any{"id": "me", "username": "tester", "nickname": "Call tester"}, map[string]any{"id": "ana", "username": "ana", "nickname": "Ana"}}}
	case "/users/profile_batch":
		value = map[string]any{"profiles": []any{}}
	case "/users/blocks":
		value = map[string]any{"users": []any{}}
	case "/roles":
		value = map[string]any{"roles": []any{}}
	case "/emojis":
		value = map[string]any{"emojis": []any{}, "has_more": false}
	case "/dms":
		value = map[string]any{"dms": []any{}}
	case "/control/ice-delay":
		var ms int64
		_, _ = fmt.Sscan(r.URL.Query().Get("ms"), &ms)
		iceDelay.Store(ms)
	case "/voice/ice-servers":
		time.Sleep(time.Duration(iceDelay.Load()) * time.Millisecond)
		value = map[string]any{"ice_servers": []any{}}
	case "/channels/chat/messages", "/channels/voice/messages":
		value = map[string]any{"messages": []any{}, "has_more": false}
	case "/stats":
		value = map[string]any{"audio": packetsAudio.Load(), "video": packetsVideo.Load(), "joins": joined.Load(), "leaves": left.Load()}
	case "/control/kick":
		peers.Range(func(k, v any) bool {
			p := k.(*peer)
			p.send(map[string]any{"type": "voice_leave", "channel_id": "voice", "user_id": "me"})
			p.closeMedia()
			return true
		})
	case "/control/disconnect":
		peers.Range(func(k, v any) bool { k.(*peer).socket.Close(); return true })
	default:
		if r.URL.Path == "/ws" {
			socket(w, r)
			return
		}
	}
	_ = json.NewEncoder(w).Encode(value)
}
func main() {
	flag.Parse()
	http.HandleFunc("/", httpAPI)
	log.Printf("local call fixture %s", *listen)
	log.Fatal(http.ListenAndServe(*listen, nil))
}
