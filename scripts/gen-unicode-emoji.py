#!/usr/bin/env python3
"""Generates papo-sdk-ui's Unicode emoji table from Unicode's and CLDR's data.

Inputs, downloaded by hand; the output's header names their versions:
  EMOJI_TEST  https://unicode.org/Public/emoji/<version>/emoji-test.txt
  ANN_*       cldr-json: cldr-annotations-full/annotations/{en,pt}/annotations.json
  DER_*       cldr-json: cldr-annotations-derived-full/annotationsDerived/{en,pt}/annotations.json

Usage:
  scripts/gen-unicode-emoji.py EMOJI_TEST ANN_EN DER_EN ANN_PT DER_PT MAX_VERSION \
      > crates/sdk/ui/src/unicode_emoji/data.rs

Keeps the fully-qualified emoji up to MAX_VERSION (what the systems' colour emoji fonts draw),
without skin-tone variants (not offered) and without components. Search text is folded as
`unicode_emoji::fold` folds a query: lower case, the accents below dropped, `_` and `-` as
spaces.
"""

import json
import re
import sys

GROUPS = {
    "Smileys & Emotion": "SmileysAndPeople",
    "People & Body": "SmileysAndPeople",
    "Animals & Nature": "AnimalsAndNature",
    "Food & Drink": "FoodAndDrink",
    "Activities": "Activities",
    "Travel & Places": "TravelAndPlaces",
    "Objects": "Objects",
    "Symbols": "Symbols",
    "Flags": "Flags",
}
SKIN_TONES = range(0x1F3FB, 0x1F400)
LINE = re.compile(r"^([0-9A-F ]+?)\s*;\s*fully-qualified\s*#\s*(\S+)\s+E(\d+\.\d+)\s+(.*)$")
# The same table as `unicode_emoji::fold`.
FOLD = {}
for plain, accented in {
    "a": "àáâãäå", "c": "ç", "e": "èéêë", "i": "ìíîï", "n": "ñ",
    "o": "òóôõö", "u": "ùúûü", "y": "ýÿ",
}.items():
    for char in accented:
        FOLD[char] = plain


def fold(text):
    out = []
    for char in text.lower():
        char = FOLD.get(char, char)
        out.append(" " if char in "_-" else char)
    return "".join(out)


def code(name):
    """`face with tears of joy` → `face_with_tears_of_joy`, `flag: Brazil` → `flag_brazil`,
    `keycap: #` → `keycap_number_sign`."""
    name = name.replace("#", " number sign ").replace("*", " asterisk ")
    return "_".join(re.findall(r"[0-9a-z]+", fold(name)))


def annotations(*paths):
    merged = {}
    for path in paths:
        with open(path, encoding="utf-8") as file:
            data = json.load(file)
        root = data.get("annotations") or data.get("annotationsDerived")
        for glyph, entry in root["annotations"].items():
            merged.setdefault(glyph, entry)
    return merged


def lookup(table, glyph):
    """CLDR keys drop U+FE0F: the glyph as written, then without it."""
    return table.get(glyph) or table.get(glyph.replace("️", ""))


def rust(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main(argv):
    test, ann_en, der_en, ann_pt, der_pt, max_version = argv[1:]
    max_version = float(max_version)
    en = annotations(ann_en, der_en)
    pt = annotations(ann_pt, der_pt)
    version_line = ""
    group = None
    rows = []
    with open(test, encoding="utf-8") as file:
        for line in file:
            if line.startswith("# Version:"):
                version_line = line[2:].strip()
            if line.startswith("# group:"):
                group = line.split(":", 1)[1].strip()
                continue
            match = LINE.match(line)
            if not match or group not in GROUPS:
                continue
            points = [int(point, 16) for point in match.group(1).split()]
            if any(point in SKIN_TONES for point in points) or float(match.group(3)) > max_version:
                continue
            glyph = "".join(chr(point) for point in points)
            name_en = match.group(4).strip()
            entry_en = lookup(en, glyph) or {}
            entry_pt = lookup(pt, glyph) or {}
            name_pt = (entry_pt.get("tts") or [name_en])[0]
            words = [name_en, name_pt, *entry_en.get("default", []), *entry_pt.get("default", [])]
            search = "|".join(dict.fromkeys(fold(word) for word in words))
            rows.append((glyph, GROUPS[group], code(name_en), name_en, name_pt, search))
    out = sys.stdout
    out.write("//! The Unicode emoji table, generated by `scripts/gen-unicode-emoji.py`; not edited by\n")
    out.write(f"//! hand. Unicode `emoji-test.txt` ({version_line}), emoji up to {max_version}, with\n")
    out.write("//! CLDR's annotations (en, pt) for names and search words.\n\n")
    out.write("use super::EmojiCategory::{\n")
    out.write("    Activities, AnimalsAndNature, Flags, FoodAndDrink, Objects, SmileysAndPeople, Symbols,\n")
    out.write("    TravelAndPlaces,\n};\nuse super::UnicodeEmoji;\n\n")
    out.write(f"pub(super) static EMOJI: [UnicodeEmoji; {len(rows)}] = [\n")
    for glyph, category, code_name, name_en, name_pt, search in rows:
        out.write(
            f"    UnicodeEmoji {{ glyph: {rust(glyph)}, category: {category}, code: {rust(code_name)}, "
            f"name_en: {rust(name_en)}, name_pt: {rust(name_pt)}, search: {rust(search)} }},\n"
        )
    out.write("];\n")


if __name__ == "__main__":
    main(sys.argv)
